// tools/collect-licenses.mjs
//
// Collects the licenses of every third-party package that ends up in the
// bundles (found through esbuild's metafile, so the list cannot drift) and
// writes:
//   licenses/<package>.LICENSE.txt
//   licenses/THIRD-PARTY-NOTICES.txt
//
// Electron / Chromium licenses are shipped by electron-builder next to the
// executable (LICENSE.electron.txt, LICENSES.chromium.html).
//
// Usage: node tools/collect-licenses.mjs
import fs from 'node:fs';
import path from 'node:path';
import * as esbuild from 'esbuild';
import { root } from './lib/load-core.mjs';

const ENTRIES = [
  'apps/octobrowser/src/main/main.ts',
  'apps/octobrowser/src/preload/tab.ts',
  'apps/octobrowser/src/renderer/browser.ts',
  'apps/octodetect/src/main/main.ts',
  'apps/octodetect/src/probe/probe.ts',
];

function pkgRootOf(input) {
  const parts = input.split(/[\\/]/);
  const i = parts.lastIndexOf('node_modules');
  if (i < 0) return null;
  const name = parts[i + 1].startsWith('@') ? `${parts[i + 1]}/${parts[i + 2]}` : parts[i + 1];
  return { name, dir: path.join(root, ...parts.slice(0, i + 1), ...name.split('/')) };
}

async function main() {
  const res = await esbuild.build({
    entryPoints: ENTRIES.map((e) => path.join(root, e)),
    bundle: true, write: false, metafile: true, outdir: path.join(root, '.tmp-licenses'),
    platform: 'node', format: 'cjs', external: ['electron'], logLevel: 'silent',
    tsconfig: path.join(root, 'tsconfig.json'), define: { __OCTO_VERSION__: '"0"' },
  });
  const pkgs = new Map();
  for (const input of Object.keys(res.metafile.inputs)) {
    const p = pkgRootOf(input);
    if (p && !pkgs.has(p.name)) pkgs.set(p.name, p.dir);
  }
  const outDir = path.join(root, 'licenses');
  fs.mkdirSync(outDir, { recursive: true });
  const rows = [];
  for (const [name, dir] of [...pkgs].sort()) {
    const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const lic = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    const target = `${name.replace('/', '__')}.LICENSE.txt`;
    if (lic) fs.copyFileSync(path.join(dir, lic), path.join(outDir, target));
    const repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? '';
    rows.push(`| ${name} | ${pj.version} | ${pj.license ?? 'see file'} | ${repo.replace(/^git\+/, '').replace(/\.git$/, '')} | ${lic ? target : 'no license file in package'} |`);
  }
  const md = `# Third-party notices

Generated by \`node tools/collect-licenses.mjs\` from the packages that are actually
bundled into Octo.su and OctoDetect.su.

| Package | Version | License | Source | File |
|---|---|---|---|---|
${rows.join('\n')}
| Electron | 44.4.5 | MIT | https://github.com/electron/electron | LICENSE.electron.txt (next to the .exe) |
| Chromium | bundled with Electron | BSD-3-Clause and others | https://www.chromium.org | LICENSES.chromium.html (next to the .exe) |

## Data downloaded at runtime (not bundled)

| List | License | Official URL |
|---|---|---|
| EasyList | GPL-3.0 / CC BY-SA 3.0 | https://easylist.to/easylist/easylist.txt |
| EasyPrivacy | GPL-3.0 / CC BY-SA 3.0 | https://easylist.to/easylist/easyprivacy.txt |
| uBlock filters | GPL-3.0 | https://ublockorigin.github.io/uAssets/filters/filters.txt |
| uBlock filters - Privacy | GPL-3.0 | https://ublockorigin.github.io/uAssets/filters/privacy.txt |

Filter lists are downloaded only when the user updates filters, from the official
URLs above, and stored unmodified in the user's data folder.

## Icons embedded in the UI

| Set | Version | License | Source | File |
|---|---|---|---|---|
| Lucide (interface icons, \`packages/shell/renderer/icons.ts\`) | 1.48.0 | ISC | https://lucide.dev | lucide.LICENSE.txt |
| Simple Icons (Apple and Linux OS glyphs) | 16.32.0 | CC0-1.0 | https://simpleicons.org | simple-icons.LICENSE.txt |

## OctoSuite artwork

The application icons in \`branding/\` (window/taskbar/installer icon) are
original works created for OctoSuite and are covered by the project license
(MPL-2.0).
`;
  fs.writeFileSync(path.join(outDir, 'THIRD-PARTY-NOTICES.txt'), md);
  console.log(`licenses: ${pkgs.size} bundled packages -> licenses/`);
}

main().catch((err) => {
  console.error('collect-licenses failed:', err?.message ?? err);
  process.exit(1);
});
